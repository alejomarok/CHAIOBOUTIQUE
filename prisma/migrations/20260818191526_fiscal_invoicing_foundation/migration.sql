-- PartialIndex: FiscalDocument — at most one currently-active (non-VOIDED)
-- fiscal document per Sale. This is the actual duplicate-invoicing guard —
-- see the FiscalDocument model's own schema comment for why this is a
-- partial index on saleId rather than a plain unique FK (a unique FK would
-- make a future credit/debit note structurally impossible to add later).
CREATE UNIQUE INDEX fiscal_document_sale_active_unique
  ON fiscal_document("saleId") WHERE status != 'VOIDED';

-- PartialIndex: FiscalDocument — the same real document identifier can
-- never be registered twice within the same mode/source namespace. Only
-- enforced once a document actually has a real "documentNumber" (an
-- ELECTRONICA_ARCA PENDING intent has none yet, and must never spuriously
-- collide with another Sale's own pending intent). COALESCE'd so two
-- MANUAL documents (sourceSystem always NULL for that mode) still
-- correctly collide against each other, while two DIFFERENT external
-- systems' independent numbering namespaces never collide with one
-- another.
CREATE UNIQUE INDEX fiscal_document_identifier_unique
  ON fiscal_document(
    mode,
    COALESCE("sourceSystem", ''),
    COALESCE("documentType", ''),
    COALESCE("pointOfSale", ''),
    "documentNumber"
  ) WHERE "documentNumber" IS NOT NULL;
